// Sample events copied from the Just Track It schedule PDFs. They stand in
// for the online database until it is connected.

import type { EventDay, ItemKind, RunGroupId, ScheduleItem, TrackEvent } from './types';

type Code =
  | 'MTG' | 'CLASS' | 'LADIES_CLASS' | 'LADIES_WRAP' | 'LUNCH' | 'PARADE'
  | 'NOV' | 'I1' | 'I2' | 'ADV' | 'LADIES' | 'LADIES_SOLO' | 'I2+ADV' | 'I1+NOV';

const CODES: Record<Code, { title: string; kind: ItemKind; groups?: RunGroupId[] }> = {
  MTG: { title: "Mandatory Driver's Meeting", kind: 'meeting' },
  CLASS: { title: 'Novice Classroom', kind: 'classroom', groups: ['novice'] },
  LADIES_CLASS: { title: 'Ladies Only Classroom', kind: 'classroom', groups: ['ladies'] },
  LADIES_WRAP: { title: 'Ladies Only Classroom Wrap Up', kind: 'classroom', groups: ['ladies'] },
  LUNCH: { title: 'Lunch Break - Track Cold', kind: 'break' },
  PARADE: { title: 'Parade Laps', kind: 'parade' },
  NOV: { title: 'Novice / Novice Solo', kind: 'track', groups: ['novice'] },
  I1: { title: 'Intermediate 1', kind: 'track', groups: ['int1'] },
  I2: { title: 'Intermediate 2', kind: 'track', groups: ['int2'] },
  ADV: { title: 'Advanced', kind: 'track', groups: ['advanced'] },
  LADIES: { title: 'Ladies Only Track Session', kind: 'track', groups: ['ladies'] },
  LADIES_SOLO: { title: 'Ladies Only Track Session (Solo)', kind: 'track', groups: ['ladies'] },
  'I2+ADV': { title: 'Int 2 and Advanced', kind: 'track', groups: ['int2', 'advanced'] },
  'I1+NOV': { title: 'Int 1 and Novice', kind: 'track', groups: ['int1', 'novice'] },
};

function day(id: string, label: string, date: string, rows: [string, string, Code][]): EventDay {
  const items: ScheduleItem[] = rows.map(([start, end, code], i) => ({
    id: `${id}-${i}`,
    start,
    end,
    ...CODES[code],
  }));
  return { id, label, date, items };
}

